const cache = new Map<string, KanjiHint>()

/** お題漢字の各画（KanjiVG の SVG パス） */
export function strokePathsOf(kanji: string): string[] {
  return DATA[kanji]?.strokes ?? []
}

export function hintOf(kanji: string): KanjiHint {
  const cached = cache.get(kanji)
  if (cached) return cached

  const entry = DATA[kanji]
  const fallback: KanjiHint = { radicalName: '？', clue: 'よく かんがえてみよう！', radicalStrokes: [] }
  if (!entry) return fallback

  const rad = entry.radical
  const radChar = rad?.element ?? ''
  const radName = RADICAL_NAMES[radChar] ?? radChar
  const total = entry.strokes.length
  // 部首が字ぜんたい（画数が同じ）なら線は見せない
  const wholeIsRadical = !rad || rad.strokes.length >= total
  const radicalStrokes = wholeIsRadical ? [] : rad!.strokes

  let clue = MANUAL_CLUES[kanji]
  if (!clue) {
    const others = entry.parts.filter((p) => p !== radChar)
    if (wholeIsRadical) {
      clue =
        entry.parts.length >= 2
          ? `「${entry.parts.join('」と「')}」で できているよ`
          : `この じ そのものが ぶしゅ「${radName}」だよ`
    } else if (others.length > 0) {
      clue = `ぶしゅは「${radName}（${radChar}）」。あとは「${others.join('」「')}」が あるよ`
    } else {
      clue = `ぶしゅは「${radName}（${radChar}）」だよ`
    }
  }

  const hint = { radicalName: radName, clue, radicalStrokes }
  cache.set(kanji, hint)
  return hint
}

